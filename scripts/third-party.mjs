// Generates THIRD_PARTY.md from the production dependency tree (license-checker-rseidelsohn, pinned dev dep)
// and fails on licenses that are unknown or not GPL-3.0-compatible.
//   node scripts/third-party.mjs          write THIRD_PARTY.md
//   node scripts/third-party.mjs --check  exit 1 if THIRD_PARTY.md is out of date (CI)
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'THIRD_PARTY.md')
const SELF = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'))

// Permissive licenses that may be combined into a GPL-3.0-or-later program.
const ALLOWED = new Set([
  'MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD', 'Apache-2.0', 'Zlib', 'Unlicense', 'CC0-1.0',
  'BlueOak-1.0.0', 'Python-2.0', 'MPL-2.0', 'LGPL-3.0-or-later', 'GPL-3.0-or-later', 'CC-BY-4.0'
])

function allowed(expr) {
  // "(MIT OR Apache-2.0)" -> any alternative allowed; "(MIT AND Zlib)" -> all parts allowed
  const s = String(expr).replace(/[()*]/g, '').trim()
  if (/ OR /i.test(s)) return s.split(/ OR /i).some((p) => allowed(p))
  if (/ AND /i.test(s)) return s.split(/ AND /i).every((p) => allowed(p))
  return ALLOWED.has(s)
}

function collect() {
  const dir = mkdtempSync(join(tmpdir(), 'mpm-licenses-'))
  try {
    const fmt = join(dir, 'format.json')
    writeFileSync(fmt, JSON.stringify({ name: '', version: '', licenses: '', repository: '', publisher: '', licenseText: '' }))
    const bin = join(ROOT, 'node_modules', 'license-checker-rseidelsohn', 'bin', 'license-checker-rseidelsohn')
    const out = execFileSync(process.execPath, [bin, '--production', '--json', '--customPath', fmt, '--start', ROOT], {
      encoding: 'utf8',
      maxBuffer: 256 * 1024 * 1024
    })
    return JSON.parse(out)
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}

function render(data) {
  const rows = Object.entries(data)
    .filter(([key]) => !key.startsWith(`${SELF.name}@`))
    .map(([key, v]) => ({ key, ...v, licenses: Array.isArray(v.licenses) ? v.licenses.join(' OR ') : String(v.licenses ?? 'UNKNOWN') }))
    .sort((a, b) => a.key.localeCompare(b.key))
  const bad = rows.filter((r) => !allowed(r.licenses))
  const lines = [
    '# Third-party software and data',
    '',
    '<!-- Generated by scripts/third-party.mjs; do not edit by hand. -->',
    '',
    'Mini Pose Master is licensed under the GNU General Public License v3.0 or later (see LICENSE).',
    '',
    '## Not bundled',
    '',
    '- **Blender** (GPL-2.0-or-later, https://www.blender.org) runs the engine jobs. It is not part of this',
    '  app: the app uses an installed Blender 5.2 or downloads the official build from download.blender.org',
    '  with your consent.',
    '- **Pose packs** (mocap data) are never bundled. Each is downloaded or chosen by you inside the app,',
    '  after you accept its license there:',
    '  - Bandai Namco Research Motion Dataset: CC BY-NC 4.0',
    '  - Ubisoft La Forge Animation Dataset (LaFAN1): CC BY-NC-ND 4.0',
    '  - CMU Graphics Lab Motion Capture Database: the database terms',
    '  Non-commercial licenses: don\'t sell prints made with these poses.',
    '- **Electron and Chromium** licenses ship with the app as `LICENSE.electron.txt` and',
    '  `LICENSES.chromium.html`.',
    '',
    `## npm packages in the app (${rows.length})`,
    '',
    '| Package | License | Source |',
    '|---|---|---|',
    ...rows.map((r) => `| ${r.key} | ${r.licenses} | ${r.repository || ''} |`),
    '',
    '## License texts',
    ''
  ]
  for (const r of rows) {
    lines.push(`### ${r.key}`, '', '```', (r.licenseText || `(no license file; declared license: ${r.licenses})`).trim(), '```', '')
  }
  return { text: lines.join('\n').replace(/\r\n/g, '\n'), bad }
}

const { text, bad } = render(collect())
if (bad.length) {
  console.error('Licenses not allowed (or unknown) in production dependencies:')
  for (const r of bad) console.error(`  ${r.key}: ${r.licenses}`)
  process.exit(1)
}
if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : ''
  if (cur !== text) {
    console.error('THIRD_PARTY.md is out of date: run `node scripts/third-party.mjs` and commit it.')
    process.exit(1)
  }
  console.log('THIRD_PARTY.md is up to date.')
} else {
  writeFileSync(OUT, text)
  console.log(`Wrote THIRD_PARTY.md (${text.length} bytes).`)
}
