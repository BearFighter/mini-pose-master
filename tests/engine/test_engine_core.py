def test_detail_height_from_normal_synthetic():
    """No figure: a flat grid with a normal map made from a known height field, in both green conventions.
    The map is found, its convention detected, and the recovered relief matches the truth."""
    H = synthetic.height_field().astype(np.float64)
    for green, label in (("opengl", "OpenGL"), ("directx", "DirectX")):
        fresh()
        img = synthetic.normal_image("relief_" + green, synthetic.normals_from_height(H, green=green))
        ob = synthetic.flat_grid("grid", img)
        found = detail.find_normal_maps(ob)
        assert len(found) == 1 and found[0]["space"] == "TANGENT" and found[0]["image"] == img, found
        assert tuple(found[0]["image"].size) == (synthetic.TEX_N, synthetic.TEX_N)
        info = importer.inspect([ob], None)
        assert len(info["normal_maps"]) == 1 and info["normal_maps"][0]["size"] == [synthetic.TEX_N] * 2
        nrm = detail.image_rgb(img)
        assert nrm.shape == (synthetic.TEX_N, synthetic.TEX_N, 3) and nrm.dtype == np.float32
        mask = detail.raster_mask(detail.uv_triangles(ob.data), synthetic.TEX_N, synthetic.TEX_N)
        assert mask.mean() > 0.99, mask.mean()
        hgt, hinfo = detail.height_from_normal(nrm, mask)
        assert hinfo["green"].startswith(label), (green, hinfo)
        a = hgt.astype(np.float64)[mask]
        b = H[mask]
        a, b = a - a.mean(), b - b.mean()
        r = float(np.dot(a, b) / np.sqrt(np.dot(a, a) * np.dot(b, b)))
        print("  %s: detail correlation r = %.4f (%s, curl ratio %s)" % (green, r, hinfo["green"], hinfo["curl_ratio"]))
        assert r > 0.9, (green, r)
        # no map on the object: nothing found
        assert detail.find_normal_maps(synthetic.flat_grid("bare")) == []


def _kit_normal_maps(name):
    """[(image, [objects using it])] of the kit's normalised scene, and the import result."""
    res = kits.project(name, "import").result("import")
    meshes = [o for o in kits.open_scene(name) if "mpm_proxy_of" not in o]
    by_img, listed = {}, []
    for o in meshes:
        for nm in detail.find_normal_maps(o):
            assert nm["space"] == "TANGENT", (name, o.name)
            by_img.setdefault(nm["image"].name, (nm["image"], []))[1].append(o)
            listed.append({"object": o.name, "material": nm["material"], "image": nm["image"].name,
                           "size": [int(nm["image"].size[0]), int(nm["image"].size[1])]})
    key = lambda d: (d["object"], d["material"], d["image"])  # noqa: E731
    assert sorted(res["normal_maps"], key=key) == sorted(listed, key=key), name
    return list(by_img.values()), res


def test_normal_maps_real_kits():
    """The kits' own normal maps are found and turned into relief; prints sizes, green convention and
    curl ratio per map. Kits whose FBX carries its textures must have at least one."""
    conventions = {}
    for name in kits.need():
        maps, _res = _kit_normal_maps(name)
        usable = [(img, users) for img, users in maps if min(img.size) > 0]
        has_textures = any(min(i.size) > 0 for i in bpy.data.images)
        print("  %s: %d normal map(s), %d with pixels" % (name, len(maps), len(usable)))
        if has_textures:
            assert usable, "%s has textures but no normal map was found" % name
        for img, users in usable:
            w, h = img.size
            nrm = detail.image_rgb(img)
            assert nrm.shape == (h, w, 3), nrm.shape
            tris = np.concatenate([detail.uv_triangles(o.data) for o in users])
            mask = detail.raster_mask(tris, w, h)
            assert 0.05 < mask.mean() <= 1.0, (name, img.name, mask.mean())
            hgt, info = detail.height_from_normal(nrm, mask)
            assert hgt.shape == (h, w) and np.isfinite(hgt).all(), (name, img.name)
            assert info["p99"] > info["p01"], (name, img.name, info)   # there is relief
            assert info["curl_ratio"] > 1.5, (name, img.name, info)    # the green convention is not a coin toss
            conventions.setdefault(info["green"], []).append("%s/%s" % (name, img.name))
            print("    %s %dx%d on %s: %s, curl ratio %s, UV coverage %.0f%%, relief p01..p99 %.2f..%.2f texels" % (
                img.name, w, h, [o.name for o in users], info["green"], info["curl_ratio"], 100 * mask.mean(),
                info["p01"], info["p99"]))
    print("  green conventions: %s" % {k: len(v) for k, v in conventions.items()})


def test_normal_maps_missing_image_files():
    """A kit whose FBX names normal-map files that did not come with it has no usable normal map: the
    import result must not offer one (an entry without pixels cannot give any detail)."""
    bad = []
    for name in kits.need():
        maps, res = _kit_normal_maps(name)
        empty = [img.name for img, _users in maps if min(img.size) == 0]
        if empty:
            print("  %s: normal-map images without pixels (files not shipped): %s" % (name, empty))
        listed = [m for m in res["normal_maps"] if min(m["size"]) == 0]
        if listed:
            bad.append((name, sorted({m["image"] for m in listed})))
    assert not bad, "import lists normal maps whose image has no pixels: %s" % bad


