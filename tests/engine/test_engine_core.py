@atexit.register
def _cleanup():
    for d in _tmp:
        shutil.rmtree(d, ignore_errors=True)


def weapon_fx(name, ext=".fbx"):
    """The repo's procedural weapon props (fixtures/out, generated by fixtures/generate.py)."""
    return os.path.join(os.environ.get("MPM_FIXTURES") or os.path.join(REPO, "fixtures", "out"), name, name + ext)


def one_kit():
    """The kit used by the tests that need a single ordinary real figure."""
    return kits.need(hard=False)[0]


def fresh():
    bpy.ops.wm.read_factory_settings(use_empty=True)


def import_job(model, args=None):
    """Run the import job on `model` in a new scratch project. Returns (project dir, code, result, error, proc)."""
    path = tempfile.mkdtemp(prefix="mpm_core_")
    _tmp.append(path)
    rel = kits.copy_source(model, path)
    return (path,) + kits.run_job(path, "import", dict(args or {}, file=rel))


def scene_of(project_dir):
    """Open a project's normalised rig/scene.blend here. Returns (meshes without proxies, their world points)."""
    bpy.ops.wm.open_mainfile(filepath=os.path.join(project_dir, "rig", "scene.blend"))
    meshes = [o for o in bpy.data.objects if o.type == 'MESH' and "mpm_proxy_of" not in o]
    return meshes, importer._all_world_verts(meshes)


def raw_extents(path):
    """Bounding-box size of a model file as Blender's importer delivers it (nothing normalised)."""
    fresh()
    meshes, _arm, _w = importer.select_objects(importer.import_model(path))
    pts = importer._all_world_verts(meshes)
    return pts.max(0) - pts.min(0)


def tagged(lines, tag):
    return [ln for ln in lines if ln.startswith("@@" + tag + " ")]


