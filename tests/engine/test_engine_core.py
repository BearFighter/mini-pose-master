def test_props_overrides():
    """args.objects is the user's own choice: props taken back in, a body part left out, nothing left."""
    name = kits.need("mesa")[0]
    model = kits.kit(name)["model"]
    ref = kits.project(name, "import").result("import")
    everything = [o["name"] for o in ref["all_objects"]]

    # the gun included again: no prop file, the gun is part of the scene
    pd, code, res, err, p = import_job(model, {"objects": {g: True for g in GUN}})
    kits.ok(code, res, err, p)
    assert all(o["included"] for o in res["all_objects"]), res["all_objects"]
    assert {o["name"] for o in res["all_objects"] if o["prop"]} == set(GUN)   # still what the rule thinks
    assert res["props"] == [] and not os.path.exists(os.path.join(pd, "props")), res["props"]
    assert sorted(o["name"] for o in res["objects"]) == sorted(everything)
    meshes, _pts = scene_of(pd)
    assert sorted(o.name for o in meshes) == sorted(everything)

    # a body part left out by hand
    part = "Tenno:BackFlap"
    assert part in everything
    pd, code, res, err, p = import_job(model, {"objects": {part: False}})
    kits.ok(code, res, err, p)
    by = {o["name"]: o for o in res["all_objects"]}
    assert by[part]["included"] is False and by[part]["prop"] is False, by[part]
    for g in GUN:
        assert by[g]["included"] is False and by[g]["prop"] is True, by[g]
    want = sorted(n for n in everything if n != part and n not in GUN)
    assert sorted(o["name"] for o in res["objects"]) == want
    meshes, _pts = scene_of(pd)
    assert sorted(o.name for o in meshes) == want
    assert any(sorted(q["objects"]) == sorted(GUN) for q in res["props"]), res["props"]
    assert abs(res["height_m"] - ref["height_m"]) < 1e-3, (res["height_m"], ref["height_m"])
    print("  left out by hand: %s; files written: %s" % (part, [q["file"] for q in res["props"]]))

    # everything left out
    pd, code, res, err, p = import_job(model, {"objects": {n: False for n in everything}})
    assert code == 1 and res is None and err is not None and err["code"] == "E_NO_MESH", (code, err)


def test_split_props_on_boxes():
    """importer.split_props on plain boxes: touching, near, far, enclosed, and the user's overrides."""
    fresh()
    body = synthetic.box("body", (0, 0, 1), (0.5, 0.3, 2.0), cuts=7)          # the biggest: size 2, gap 0.06
    touching = synthetic.box("touching", (0.35, 0, 1.5), (0.2, 0.2, 0.2), cuts=3)    # shares the body's side
    near = synthetic.box("near", (-0.39, 0, 1.0), (0.2, 0.2, 0.2), cuts=3)           # 0.04 from the body
    far = synthetic.box("far", (1.5, 0, 0.1), (0.2, 0.2, 0.2), cuts=3)               # 1.15 away
    chained = synthetic.box("chained", (0.55, 0, 1.5), (0.2, 0.2, 0.2), cuts=3)      # touches `touching` only
    inside = synthetic.box("inside", (0, 0, 1.0), (0.44, 0.24, 0.5), cuts=3)         # enclosed, 0.03 from the walls
    shell = synthetic.box("shell", (0, 0, 1.9), (0.6, 0.4, 0.3))   # 8 corners far from the body, faces around it
    meshes = [body, touching, near, far, chained, inside, shell]
    keep, props, auto = importer.split_props(meshes)
    assert auto == {"body": False, "touching": False, "near": False, "far": True, "chained": False,
                    "inside": False, "shell": False}, auto
    assert [o.name for o in props] == ["far"] and len(keep) == 6
    # overrides win in both directions; `auto` still tells what the rule thinks
    keep, props, auto2 = importer.split_props(meshes, None, {"far": True, "near": False})
    assert auto2 == auto
    assert sorted(o.name for o in props) == ["near"] and far in keep
    try:
        importer.split_props(meshes, None, {o.name: False for o in meshes})
    except protocol.MpmError as e:
        assert e.code == "E_NO_MESH"
    else:
        raise AssertionError("E_NO_MESH not raised")
    # one object: nothing to split
    keep, props, auto = importer.split_props([body])
    assert keep == [body] and props == [] and auto == {"body": False}


def test_prop_groups_on_boxes():
    """importer.prop_groups: props that touch are one prop."""
    fresh()
    a = synthetic.box("a", (0, 0, 0), (0.6, 0.05, 0.1), cuts=3)
    b = synthetic.box("b", (0.2, 0, -0.1), (0.05, 0.05, 0.1), cuts=3)     # under a, touching
    c = synthetic.box("c", (0.0, 0, 0.065), (0.3, 0.02, 0.02), cuts=3)     # 0.005 above a: within 5 % of 0.6
    d = synthetic.box("d", (3.0, 0, 0), (0.2, 0.2, 0.2), cuts=3)           # elsewhere
    groups = importer.prop_groups([a, b, c, d])
    assert sorted(sorted(o.name for o in g) for g in groups) == [["a", "b", "c"], ["d"]], groups
    assert importer.prop_groups([]) == []


