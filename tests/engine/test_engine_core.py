def test_printable_voxel_budget():
    """contracts section 14 on a real kit: within budget as is; coarsened up to 2x and reported; else refused."""
    meshes = [o for o in kits.open_scene(one_kit()) if "mpm_proxy_of" not in o]
    s = printable.Settings(height=40, flatten=0.5, voxel=0.5, base_diameter=0)
    saved = printable.VOXEL_BUDGET
    try:
        with tempfile.TemporaryDirectory() as d:
            out = os.path.join(d, "a.stl")
            _ob, rep = printable.make_printable(meshes, s, out)
            est = rep["voxel_estimate"]
            assert "voxel_coarsened_to" not in rep
            # needs ~1.41x: coarsened and reported
            printable.VOXEL_BUDGET = est // 2
            _ob, rep2 = printable.make_printable(meshes, s, out)
            assert 0.5 < rep2["voxel_coarsened_to"] <= 1.0 + 1e-9, rep2.get("voxel_coarsened_to")
            # needs ~3.2x: refused
            printable.VOXEL_BUDGET = max(1, est // 10)
            try:
                printable.make_printable(meshes, s, out)
            except protocol.MpmError as e:
                assert e.code == "E_BUDGET", e.code
            else:
                raise AssertionError("E_BUDGET not raised")
    finally:
        printable.VOXEL_BUDGET = saved


def test_stlcheck_cube():
    """stlcheck on a unit cube written by hand (no Blender geometry involved)."""
    with tempfile.TemporaryDirectory() as d:
        p = os.path.join(d, "cube.stl")
        synthetic.write_cube_stl(p)
        r = stlcheck.check(p)
        assert r["tris"] == 12 and r["open_edges"] == 0 and r["nonmanifold_edges"] == 0, r
        assert abs(r["volume"] - 1.0) < 1e-9, r
        assert np.allclose(r["dims"], [1, 1, 1]) and r["floor_z"] == 0.0
        # the bottom face (2 tris, normal -z, z=0 < floor+0.1) is contact; centroids x>=0 -> L only
        assert abs(r["sole_contact"]["L"] - 1.0) < 1e-9 and r["sole_contact"]["R"] == 0.0, r
        p2 = os.path.join(d, "open.stl")
        synthetic.write_cube_stl(p2, drop_face=True)
        r2 = stlcheck.check(p2)
        assert r2["tris"] == 10 and r2["open_edges"] == 4, r2
