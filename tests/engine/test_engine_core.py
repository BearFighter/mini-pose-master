def test_import_reexported_yup_and_cm():
    """A real kit written out again as Y up, in centimetres, and both (kit_variants.reexported: the
    geometry itself is turned / scaled, the FBX header still says Z up and metres), plus the FBX exporter's
    own Y-up centimetre export. The suggested orientation and unit scale must bring each one back to the
    figure of the direct import, facing -Y."""
    name = one_kit()
    _m, ref = scene_of(kits.project(name, "import").dir)
    r_lo, r_hi, r_mean = ref.min(0), ref.max(0), ref.mean(0)
    H = float(r_hi[2] - r_lo[2])
    cases = (("yup", {"yup": True}, {"up": "Y", "forward": "Z", "unit_scale": 1.0}),
             ("cm", {"cm": True}, {"up": "Z", "forward": "-Y", "unit_scale": 0.01}),
             ("yup_cm", {"yup": True, "cm": True}, {"up": "Y", "forward": "Z", "unit_scale": 0.01}),
             ("declared_yup_cm", {"declared": True}, {"up": "Z", "forward": "-Y", "unit_scale": 0.01}))
    for label, kw, want in cases:
        fbx = kit_variants.reexported(name, **kw)
        ext = raw_extents(fbx)   # the file really is in another convention
        tall = 1 if want["up"] == "Y" else 2
        assert abs(ext[tall] * want["unit_scale"] - H) < 1e-3 and int(np.argmax(ext)) == tall, (label, ext, H)
        pr = kits.project_from_model(fbx, upto="import", label="reexp_" + label)
        res = pr.results["import"]
        sug = {k: res["suggested_orientation"][k] for k in want}
        assert sug == want and res["orientation_used"] == want, (label, res["suggested_orientation"])
        meshes, pts = scene_of(pr.dir)
        lo, hi = pts.min(0), pts.max(0)
        assert abs(res["height_m"] - H) < 1e-3, (label, res["height_m"], H)
        assert np.abs((hi - lo) - (r_hi - r_lo)).max() < 1e-3, (label, hi - lo, r_hi - r_lo)
        assert np.abs(lo - r_lo).max() < 1e-3 and np.abs(hi - r_hi).max() < 1e-3, (label, lo, hi)
        # facing: the same figure the same way round (a half turn would flip the centroid's y), toes to -Y
        assert np.abs(pts.mean(0) - r_mean).max() < 1e-3, (label, pts.mean(0), r_mean)
        assert importer.suggest_orientation(meshes)["forward"] == "-Y", label
        print("  %s %s: raw extents %s -> suggested %s, height %.4f m (direct %.4f)" % (
            name, label, np.round(ext, 3).tolist(), sug, res["height_m"], H))


_obj_cases = {}


def _obj_case(name):
    """Import the .obj shipped beside the kit's .fbx. Returns None when there is none, else a dict."""
    if name in _obj_cases:
        return _obj_cases[name]
    obj = kit_variants.find_obj(name)
    if obj is None:
        _obj_cases[name] = None
        return None
    fbx = kits.project(name, "import")
    f_res = fbx.result("import")
    _m, ref = scene_of(fbx.dir)
    raw = raw_extents(obj)
    pr = kits.project_from_model(obj, upto="import", label=name + "_obj")
    res = pr.results["import"]
    meshes, pts = scene_of(pr.dir)
    dims, ref_dims = pts.max(0) - pts.min(0), ref.max(0) - ref.min(0)
    _obj_cases[name] = {
        "name": name, "file": os.path.basename(obj), "raw": raw, "res": res, "fbx": f_res,
        "dims": dims, "ref_dims": ref_dims,
        "toes": importer.suggest_orientation(meshes)["forward"],
        "turned": bool((dims[0] > dims[1]) != (ref_dims[0] > ref_dims[1])),   # width and depth swapped
        "merged_prop": bool(f_res["props"]) and len(res["all_objects"]) == 1}
    return _obj_cases[name]


def _obj_report(c):
    return "  %s %s: %d object(s), %d tris (fbx %d); raw extents %s; suggested %s; height %.4f m (fbx %.4f), " \
           "dims off by %s mm%s" % (
               c["name"], c["file"], len(c["res"]["all_objects"]), c["res"]["tri_count"], c["fbx"]["tri_count"],
               np.round(c["raw"], 2).tolist(),
               {k: c["res"]["suggested_orientation"][k] for k in ("up", "forward", "unit_scale")},
               c["res"]["height_m"], c["fbx"]["height_m"],
               np.round((c["dims"] - c["ref_dims"]) * 1000, 2).tolist(),
               ", TURNED a quarter turn (width and depth swapped)" if c["turned"] else "")


def _obj_same_figure(c):
    """What is wrong with the OBJ import compared with the FBX import of the same kit (empty = nothing)."""
    bad = []
    if abs(c["res"]["height_m"] - c["fbx"]["height_m"]) >= 2e-3:
        bad.append("height %.4f m, fbx %.4f m" % (c["res"]["height_m"], c["fbx"]["height_m"]))
    if np.abs(c["dims"] - c["ref_dims"]).max() >= 2e-3:
        bad.append("dims differ by %s mm" % np.round((c["dims"] - c["ref_dims"]) * 1000, 1).tolist())
    if c["turned"] or c["toes"] != "-Y":
        bad.append("not facing -Y (suggested forward %r on the raw file)" % c["res"]["suggested_orientation"]["forward"])
    return bad


def test_import_obj_beside_fbx():
    """Kits that ship an .obj beside the .fbx: the OBJ import gives the same figure (2 mm). The OBJs are
    authored in centimetres, so this is the unit suggestion at work on real files."""
    failed, seen = [], 0
    for name in kits.need():
        c = _obj_case(name)
        if c is None:
            print("  %s: no .obj beside the .fbx" % name)
            continue
        print(_obj_report(c))
        if c["merged_prop"]:
            continue   # see test_import_obj_with_prop_merged_in
        seen += 1
        bad = _obj_same_figure(c)
        if bad:
            failed.append((name, bad))
    assert not failed, failed
    assert seen, "no kit with an .obj beside its .fbx"


def test_import_obj_with_prop_merged_in():
    """A kit whose FBX has the prop as separate objects but whose OBJ is one merged object (prop included):
    the OBJ import must still give the character of the FBX import, facing -Y."""
    cases = [c for c in (_obj_case(n) for n in kits.need()) if c is not None and c["merged_prop"]]
    if not cases:
        raise unittest.SkipTest("no kit ships an .obj with its prop merged into one object")
    failed = []
    for c in cases:
        print(_obj_report(c))
        bad = _obj_same_figure(c)
        if bad:
            failed.append((c["name"], bad))
    assert not failed, "the prop merged into the OBJ's single object is taken for the character: %s" % failed


def test_import_dense_proxy():
    """A real kit subdivided past the proxy limit: hidden <name>__proxy copies of at most 300k triangles,
    the originals kept."""
    name = one_kit()
    pr = kits.project_from_model(kits.dense_model(name), upto="import", label=name + "_dense")
