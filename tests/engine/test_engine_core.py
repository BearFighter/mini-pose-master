    for o in res["objects"]:   # the originals are still there, at full density
        src = bpy.data.objects.get(o["name"])
        assert src is not None and importer._tri_count(src.data) == o["tris"], o["name"]
    ref = kits.project(name, "import").result("import")
    assert abs(res["height_m"] - ref["height_m"]) < 1e-3, (res["height_m"], ref["height_m"])
    print("  %s dense: %d triangles, proxies %d triangles in %d objects" % (name, res["tri_count"], total, len(proxies)))


