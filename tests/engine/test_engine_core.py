GUN = ("GunHandle", "GunMain", "GunRail")


def _bounds_from_glb(path):
    """(node names carrying a mesh, bounding-box size in metres) of a static GLB written in metres."""
    gj = parse_glb_json(path)
    lo, hi = np.full(3, np.inf), np.full(3, -np.inf)
    names = []
    for n in gj["nodes"]:
        if "mesh" not in n:
            continue
        names.append(n["name"])
        t = np.array(n.get("translation", (0, 0, 0)), float)
        assert "rotation" not in n and "scale" not in n and "matrix" not in n, n
        for prim in gj["meshes"][n["mesh"]]["primitives"]:
            acc = gj["accessors"][prim["attributes"]["POSITION"]]
            lo, hi = np.minimum(lo, np.array(acc["min"]) + t), np.maximum(hi, np.array(acc["max"]) + t)
    return names, hi - lo


